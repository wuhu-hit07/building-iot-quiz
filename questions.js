const OPTION_KEYS = ["A", "B", "C", "D"];

function rotateChoices(question, offset) {
  if (question.type === "judgment" || !offset) return question;
  const remap = new Map();
  const choices = question.choices
    .map((choice, index) => {
      const newIndex = (index - offset + 4) % 4;
      remap.set(choice.key, OPTION_KEYS[newIndex]);
      return { ...choice, key: OPTION_KEYS[newIndex] };
    })
    .sort((a, b) => OPTION_KEYS.indexOf(a.key) - OPTION_KEYS.indexOf(b.key));
  const answer = Array.isArray(question.answer)
    ? question.answer.map((key) => remap.get(key)).sort()
    : remap.get(question.answer);
  return { ...question, choices, answer };
}

const ORDERED_QUESTIONS = RAW_QUESTIONS.map((question, index) =>
  rotateChoices(question, CHOICE_ROTATION[index % CHOICE_ROTATION.length]),
);

window.QUIZ_QUESTIONS = ORDERED_QUESTIONS.map((item, index) => ({
  ...item,
  number: index + 1,
  moduleName: MODULE_META[item.module].name,
  typeLabel: TYPE_LABELS[item.type],
  evidenceLabel: EVIDENCE_LABELS[item.evidence],
}));

const countBy = (key) =>
  ORDERED_QUESTIONS.reduce((acc, item) => {
    acc[item[key]] = (acc[item[key]] || 0) + 1;
    return acc;
  }, {});

window.QUIZ_META = {
  title: "建筑工程物联网 · 专项刷题",
  book: "《建筑工程物联网》",
  isbn: "978-7-04-061607-1",
  generatedAt: "2026-10-30",
  total: ORDERED_QUESTIONS.length,
  modules: Object.entries(MODULE_META).map(([id, meta]) => ({
    id,
    name: meta.name,
    short: meta.short,
    shortLabel: meta.shortLabel,
    count: ORDERED_QUESTIONS.filter((q) => q.module === id).length,
  })),
  typeCounts: countBy("type"),
  evidenceCounts: countBy("evidence"),
  difficultyCounts: countBy("difficulty"),
};
